// Self-contained research PDF builder — no headless browser required.
// Renders white pages with black text and a dull-grey Cogerphere AI Labs mark.
// Previously this used Playwright's chromium.launch(), which fails in any
// environment without downloaded browsers (headless_shell missing) and breaks
// downloads entirely. This writer uses only base-14 PDF fonts.

const PAGE_W = 595.28; // A4
const PAGE_H = 841.89;
const MARGIN = 56.7; // ~20mm
const CONTENT_W = PAGE_W - MARGIN * 2;
const FOOTER_Y = 32;

const BRANDING = "Generated by Cogerphere AI Labs - Cobentt";

type Block =
  | { kind: "h"; text: string }
  | { kind: "p"; text: string }
  | { kind: "bullet"; text: string }
  | { kind: "number"; num: string; text: string }
  | { kind: "code"; text: string }
  | { kind: "quote"; text: string };

function ascii(s: string): string {
  return String(s ?? "")
    .replace(/[“”„]/g, '"')
    .replace(/[‘’]/g, "'")
    .replace(/[—–]/g, "-")
    .replace(/[…]/g, "...")
    .replace(/[•]/g, "-")
    .replace(/[^\x20-\x7E\n]/g, "")
    .trim();
}

function inline(s: string): string {
  let t = String(s ?? "");
  t = t.replace(/!\[([^\]]*)\]\([^)]*\)/g, "$1");
  t = t.replace(/\[([^\]]*)\]\(([^)]*)\)/g, "$1");
  t = t.replace(/(\*\*|__)(.*?)\1/g, "$2");
  t = t.replace(/(\*|_)(.*?)\1/g, "$2");
  t = t.replace(/`([^`]*)`/g, "$1");
  t = t.replace(/<[^>]*>/g, "");
  t = t.replace(/^#{1,6}\s+/, "");
  t = t.replace(/^>\s?/, "");
  return ascii(t);
}

function markdownToBlocks(md: string): Block[] {
  const lines = String(md || "").split("\n");
  const blocks: Block[] = [];
  let inCode = false;
  let codeBuf: string[] = [];
  let paraBuf: string[] = [];

  const flushPara = () => {
    if (paraBuf.length) {
      const t = inline(paraBuf.join(" "));
      if (t) blocks.push({ kind: "p", text: t });
      paraBuf = [];
    }
  };

  for (const raw of lines) {
    const line = raw.replace(/\r$/, "");
    if (/^```/.test(line.trim())) {
      if (inCode) {
        inCode = false;
        if (codeBuf.length) blocks.push({ kind: "code", text: ascii(codeBuf.join("\n")).slice(0, 2000) });
        codeBuf = [];
      } else {
        inCode = true;
        flushPara();
      }
      continue;
    }
    if (inCode) {
      codeBuf.push(line);
      continue;
    }
    const trimmed = line.trim();
    if (!trimmed) {
      flushPara();
      continue;
    }
    const h = trimmed.match(/^(#{1,4})\s+(.*)/);
    if (h) {
      flushPara();
      const t = inline(h[2]);
      if (t) blocks.push({ kind: "h", text: t });
      continue;
    }
    const q = trimmed.match(/^>\s?(.*)/);
    if (q) {
      flushPara();
      const t = inline(q[1]);
      if (t) blocks.push({ kind: "quote", text: t });
      continue;
    }
    const ul = trimmed.match(/^[-*]\s+(.*)/);
    if (ul) {
      flushPara();
      const t = inline(ul[1]);
      if (t) blocks.push({ kind: "bullet", text: t });
      continue;
    }
    const ol = trimmed.match(/^(\d+)[.)]\s+(.*)/);
    if (ol) {
      flushPara();
      const t = inline(ol[2]);
      if (t) blocks.push({ kind: "number", num: ol[1], text: t });
      continue;
    }
    paraBuf.push(trimmed);
  }
  flushPara();
  if (codeBuf.length) blocks.push({ kind: "code", text: ascii(codeBuf.join("\n")).slice(0, 2000) });
  return blocks;
}

function escPdf(s: string): string {
  return s.replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");
}

// Rough width estimate: Helvetica avg ~0.5em, bold ~0.55em, courier 0.6em.
function wrap(text: string, fontSize: number, maxW: number, scale = 0.5): string[] {
  const words = text.split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let cur = "";
  let curW = 0;
  const spaceW = fontSize * scale;
  for (const w of words) {
    const wW = w.length * fontSize * scale;
    if (!cur) {
      // Single very long word: hard-split it.
      if (wW > maxW) {
        const charsPerLine = Math.max(1, Math.floor(maxW / (fontSize * scale)));
        for (let i = 0; i < w.length; i += charsPerLine) {
          lines.push(w.slice(i, i + charsPerLine));
        }
        continue;
      }
      cur = w;
      curW = wW;
    } else if (curW + spaceW + wW <= maxW) {
      cur += " " + w;
      curW += spaceW + wW;
    } else {
      lines.push(cur);
      if (wW > maxW) {
        const charsPerLine = Math.max(1, Math.floor(maxW / (fontSize * scale)));
        for (let i = 0; i < w.length; i += charsPerLine) {
          const chunk = w.slice(i, i + charsPerLine);
          if (i + charsPerLine >= w.length) {
            cur = chunk;
            curW = chunk.length * fontSize * scale;
          } else {
            lines.push(chunk);
          }
        }
      } else {
        cur = w;
        curW = wW;
      }
    }
  }
  if (cur) lines.push(cur);
  return lines.length ? lines : [""];
}

interface Page {
  ops: string[];
}

function newPage(): { page: Page; y: number } {
  const page: Page = {
    ops: [
      // Explicit white background so the PDF never inherits a dark theme.
      "1 1 1 rg",
      `0 0 ${PAGE_W.toFixed(2)} ${PAGE_H.toFixed(2)} re f`,
      "0 0 0 rg",
    ],
  };
  return { page, y: PAGE_H - MARGIN };
}

function ensureRoom(pages: Page[], state: { page: Page; y: number }, needed: number) {
  if (state.y - needed < MARGIN + 24) {
    const n = newPage();
    pages.push(n.page);
    state.page = n.page;
    state.y = n.y;
  }
}

function drawText(
  state: { page: Page; y: number },
  text: string,
  opts: { font: string; size: number; gray?: [number, number, number]; x?: number; lh?: number }
) {
  const x = opts.x ?? MARGIN;
  state.y -= opts.lh ?? opts.size * 1.35;
  const [r, g, b] = opts.gray ?? [0, 0, 0];
  state.page.ops.push(
    `BT /${opts.font} ${opts.size} Tf ${r} ${g} ${b} rg ${x.toFixed(2)} ${state.y.toFixed(2)} Td (${escPdf(text)}) Tj ET`
  );
}

function drawWrapped(
  pages: Page[],
  state: { page: Page; y: number },
  text: string,
  opts: { font: string; size: number; x?: number; maxW?: number; scale?: number; lh?: number; gray?: [number, number, number] }
) {
  const maxW = opts.maxW ?? CONTENT_W - ((opts.x ?? MARGIN) - MARGIN);
  for (const line of wrap(text, opts.size, maxW, opts.scale ?? 0.5)) {
    ensureRoom(pages, state, opts.size * 1.5);
    drawText(state, line, opts);
  }
}

// eslint-disable-next-line @typescript-eslint/no-explicit-any
export async function buildResearchPdf(artifact: any): Promise<Buffer> {
  const title = ascii(artifact?.title || "Research Report").slice(0, 200) || "Research Report";
  const summary = ascii(artifact?.summary || "");
  const sections: Array<{ heading?: string; content?: string }> = Array.isArray(artifact?.sections)
    ? artifact.sections
    : [];
  const sources: Array<{ title?: string; url?: string }> = Array.isArray(artifact?.sources) ? artifact.sources : [];

  const pages: Page[] = [];
  const first = newPage();
  pages.push(first.page);
  const state = { page: first.page, y: first.y };

  // Title — black on white.
  drawWrapped(pages, state, title, { font: "F2", size: 20, scale: 0.55, lh: 26 });
  // Thin rule under title.
  state.y -= 8;
  ensureRoom(pages, state, 10);
  state.page.ops.push(`0.83 0.83 0.86 RG 0.8 w ${MARGIN.toFixed(2)} ${state.y.toFixed(2)} ${(CONTENT_W).toFixed(2)} 0 re S 0 0 0 rg`);
  state.y -= 10;

  if (summary) {
    ensureRoom(pages, state, 30);
    drawText(state, "Executive Summary", { font: "F2", size: 11 });
    state.y -= 2;
    drawWrapped(pages, state, summary, { font: "F1", size: 10, scale: 0.5 });
    state.y -= 8;
  }

  sections.forEach((s, idx) => {
    const heading = ascii(s.heading || `Section ${idx + 1}`);
    ensureRoom(pages, state, 40);
    state.y -= 6;
    drawWrapped(pages, state, `${idx + 1}. ${heading}`, { font: "F2", size: 13, scale: 0.55 });
    state.y -= 2;
    const blocks = markdownToBlocks(s.content || "");
    if (!blocks.length) state.y -= 4;
    for (const b of blocks) {
      if (b.kind === "h") {
        ensureRoom(pages, state, 24);
        state.y -= 2;
        drawWrapped(pages, state, b.text, { font: "F2", size: 11, scale: 0.55 });
      } else if (b.kind === "bullet") {
        drawWrapped(pages, state, `- ${b.text}`, { font: "F1", size: 10, x: MARGIN + 12, maxW: CONTENT_W - 12 });
      } else if (b.kind === "number") {
        drawWrapped(pages, state, `${b.num}. ${b.text}`, { font: "F1", size: 10, x: MARGIN + 12, maxW: CONTENT_W - 12 });
      } else if (b.kind === "code") {
        state.y -= 2;
        for (const cl of b.text.split("\n").slice(0, 40)) {
          ensureRoom(pages, state, 16);
          drawText(state, (cl || " ").slice(0, 95), { font: "F3", size: 8.5, lh: 12 });
        }
        state.y -= 2;
      } else if (b.kind === "quote") {
        drawWrapped(pages, state, b.text, { font: "F1", size: 10, x: MARGIN + 12, maxW: CONTENT_W - 12, gray: [0.25, 0.25, 0.27] });
      } else {
        drawWrapped(pages, state, b.text, { font: "F1", size: 10 });
      }
    }
    state.y -= 6;
  });

  if (sources.length) {
    ensureRoom(pages, state, 40);
    state.y -= 4;
    drawText(state, "Sources", { font: "F2", size: 12 });
    state.y -= 2;
    sources.slice(0, 60).forEach((src, i) => {
      const t = ascii(src.title || `Source ${i + 1}`);
      const u = ascii(src.url || "");
      const line = u ? `${i + 1}. ${t} - ${u}` : `${i + 1}. ${t}`;
      drawWrapped(pages, state, line.slice(0, 300), { font: "F1", size: 8.5, scale: 0.5 });
    });
  }

  // Dull-grey branding mark at the end + on every page footer.
  ensureRoom(pages, state, 30);
  state.y -= 10;
  drawWrapped(pages, state, BRANDING, { font: "F1", size: 9, gray: [0.71, 0.71, 0.71] });

  // Page footers (dull grey, does not affect body colours).
  for (const p of pages) {
    p.ops.push(
      `BT /F1 8 Tf 0.71 0.71 0.71 rg ${(PAGE_W / 2 - 90).toFixed(2)} ${FOOTER_Y - 14} Td (${escPdf(BRANDING)}) Tj ET`
    );
  }

  // Assemble PDF.
  const objects: string[] = [];
  // Reserve numbers: 1 catalog, 2 pages, 3 F1, 4 F2, 5 F3, then 2 per page.
  const pageStart = 6;
  const pageRefs: string[] = [];
  pages.forEach((_, i) => {
    const pageObj = pageStart + i * 2;
    pageRefs.push(`${pageObj} 0 R`);
  });
  objects[1] = `<< /Type /Catalog /Pages 2 0 R >>`;
  objects[2] = `<< /Type /Pages /Kids [${pageRefs.join(" ")}] /Count ${pages.length} >>`;
  objects[3] = `<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>`;
  objects[4] = `<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>`;
  objects[5] = `<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>`;
  const contents: Buffer[] = pages.map((p) => Buffer.from(p.ops.join("\n") + "\n", "latin1"));
  pages.forEach((_, i) => {
    const pageObj = pageStart + i * 2;
    const contentObj = pageObj + 1;
    objects[pageObj] =
      `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${PAGE_W} ${PAGE_H}] ` +
      `/Resources << /Font << /F1 3 0 R /F2 4 0 R /F3 5 0 R >> >> /Contents ${contentObj} 0 R >>`;
    objects[contentObj] = `<< /Length ${contents[i].length} >>\nstream\n` + contents[i].toString("latin1") + `endstream`;
  });

  let out = `%PDF-1.4\n`;
  const offsets: number[] = [];
  const maxId = pageStart + pages.length * 2 - 1;
  for (let id = 1; id <= maxId; id++) {
    offsets[id] = Buffer.byteLength(out, "latin1");
    out += `${id} 0 obj\n${objects[id]}\nendobj\n`;
  }
  const xrefPos = Buffer.byteLength(out, "latin1");
  out += `xref\n0 ${maxId + 1}\n0000000000 65535 f \n`;
  for (let id = 1; id <= maxId; id++) {
    out += `${String(offsets[id]).padStart(10, "0")} 00000 n \n`;
  }
  out += `trailer\n<< /Size ${maxId + 1} /Root 1 0 R >>\nstartxref\n${xrefPos}\n%%EOF`;
  return Buffer.from(out, "latin1");
}
