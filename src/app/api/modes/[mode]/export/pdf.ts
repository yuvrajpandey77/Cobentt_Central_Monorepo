import { chromium } from "playwright";

const ESC = (s: string) => String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function renderMarkdown(md: string): string {
  let text = String(md || "");

  // Code blocks first
  text = text.replace(/```(\w+)?\n([\s\S]*?)```/g, (_m, _lang: string, code: string) => `<pre class="code">${ESC(code)}</pre>`);

  // Inline formatting
  text = text.replace(/\*\*(.*?)\*\*/g, "<strong>$1</strong>");
  text = text.replace(/\*(.*?)\*/g, "<em>$1</em>");
  text = text.replace(/\[(.*?)\]\((.*?)\)/g, '<a href="$2">$1</a>');

  // Lists (group consecutive `- ` or `* ` lines into <ul>)
  text = text.replace(/((?:^|\n)[ \t]*[-*][ \t]+[^\n]+(?:\n[ \t]*[-*][ \t]+[^\n]*)*)/g, (block) => {
    const items = block
      .split("\n")
      .filter((l) => l.trim())
      .map((l) => `<li>${l.replace(/^[ \t]*[-*][ \t]+/, "")}</li>`)
      .join("");
    return `\n<ul>${items}</ul>`;
  });

  // Ordered lists
  text = text.replace(/((?:^|\n)[ \t]*\d+\.[ \t]+[^\n]+(?:\n[ \t]*\d+\.[ \t]+[^\n]*)*)/g, (block) => {
    const items = block
      .split("\n")
      .filter((l) => l.trim())
      .map((l) => `<li>${l.replace(/^[ \t]*\d+\.\s*/, "")}</li>`)
      .join("");
    return `\n<ol>${items}</ol>`;
  });

  // Headings
  text = text.replace(/^##### (.*)$/gm, "<h5>$1</h5>");
  text = text.replace(/^#### (.*)$/gm, "<h4>$1</h4>");
  text = text.replace(/^### (.*)$/gm, "<h3>$1</h3>");
  text = text.replace(/^## (.*)$/gm, "<h2>$1</h2>");
  text = text.replace(/^# (.*)$/gm, "<h1>$1</h1>");

  // Paragraphs
  text = text
    .replace(/^([^\n<][^\n]*)$/gm, (m) => (m.trim() ? `<p>${m.trim()}</p>` : ""))
    .replace(/\n{2,}/g, "\n")
    .replace(/(<\/p>)\s*\n\s*(<p>)/g, "</p><p>")
    .replace(/<p>\s*<\/p>/g, "");

  return text.trim();
}

// eslint-disable-next-line @typescript-eslint/no-explicit-any
export async function buildResearchPdf(artifact: any): Promise<Buffer> {
  const sections = Array.isArray(artifact.sections) ? artifact.sections : [];
  const sources = Array.isArray(artifact.sources) ? artifact.sources : [];

  const sectionsHtml = sections
    .map((s: { heading?: string; content?: string }) => {
      const heading = String(s.heading || "").trim();
      let content = renderMarkdown(s.content || "");

      // Avoid duplicating the heading: drop the first heading line if it equals the section heading
      if (heading) {
        content = content.replace(new RegExp(`^<h[1-4]>${heading.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}</h[1-4]>\\s*`), "");
      }

      return `
        <section class="report-section">
          <h2 class="section-title">${ESC(heading)}</h2>
          <div class="content">${content}</div>
        </section>`;
    })
    .join("");

  const sourcesHtml = sources
    .map((s: { title?: string; url?: string }) => `<li><span class="src-title">${ESC(s.title || "")}</span>${s.url ? ` — ${ESC(s.url)}` : ""}</li>`)
    .join("");

  const html = `<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8" />
<style>
  @page { margin: 20mm; }
  body { font-family: 'Georgia', 'Times New Roman', serif; color: #1a1a1a; line-height: 1.65; font-size: 11pt; }
  h1 { font-size: 20pt; color: #1a1a1a; border-bottom: 2px solid #d4d4d8; padding-bottom: 8px; margin: 0 0 16px; }
  .summary { background: #f4f4f5; border-left: 4px solid #a1a1aa; padding: 12px 16px; margin: 16px 0; }
  .report-section { margin-bottom: 20px; }
  .section-title { font-size: 14pt; color: #1a1a1a; margin: 24px 0 8px; }
  .content { margin-top: 6px; }
  .content p { margin: 6px 0; }
  .content h1, .content h2, .content h3, .content h4, .content h5 { color: #1a1a1a; margin: 14px 0 6px; }
  .content h2 { font-size: 13pt; }
  .content h3 { font-size: 12pt; }
  .content h4 { font-size: 11.5pt; }
  .content ul, .content ol { margin: 6px 0; padding-left: 20px; }
  .content li { margin-bottom: 4px; }
  .content a { color: #3f3f46; }
  pre.code { background: #f4f4f5; color: #1a1a1a; padding: 12px; border-radius: 4px; overflow-x: auto; font-family: 'Courier New', monospace; font-size: 9.5pt; }
  .sources { margin-top: 24px; border-top: 2px solid #d4d4d8; padding-top: 12px; }
  .sources li { margin-bottom: 6px; }
  .src-title { font-weight: 600; }
  footer { margin-top: 32px; color: #71717a; font-size: 9pt; }
</style>
</head>
<body>
  <h1>${ESC(artifact.title || "Research Report")}</h1>
  ${artifact.summary ? `<div class="summary">${ESC(artifact.summary)}</div>` : ""}
  ${sectionsHtml}
  ${sources.length ? `<div class="sources"><h2>Sources</h2><ul>${sourcesHtml}</ul></div>` : ""}
  <footer>Generated by Cobentt — Cogerphere AI Labs</footer>
</body>
</html>`;

  const browser = await chromium.launch();
  try {
    const page = await browser.newPage();
    await page.setContent(html, { waitUntil: "networkidle" });
    const pdf = await page.pdf({ format: "A4", printBackground: true });
    return Buffer.from(pdf);
  } finally {
    await browser.close();
  }
}
