/**
 * Parses Forge compilation output to extract errors and warnings
 */
export function parseForgeOutput(stdout: string, stderr: string, exitCode: number): ForgeErrorInfo {
  const output = stderr + stdout;
  
  // Extract errors (lines containing "Error")
  const errors: string[] = [];
  const warnings: string[] = [];
  
  const lines = output.split('\n');
  
  for (const line of lines) {
    if (line.includes('Error') || line.includes('error')) {
      errors.push(line.trim());
    } else if (line.includes('Warning') || line.includes('warning')) {
      warnings.push(line.trim());
    }
  }
  
  // If no errors found but exit code indicates failure, capture all output
  if (exitCode !== 0 && errors.length === 0) {
    errors.push('Compilation failed. See full output for details.');
    errors.push(output.substring(0, 500));
  }
  
  return {
    errors,
    warnings,
    compilationStatus: exitCode === 0 ? 'success' : 'failure',
    exitCode
  };
}
