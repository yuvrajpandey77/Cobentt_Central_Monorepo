/**
 * Generates a contract with iterative refinement
 */
export async function generateContractWithIteration(
  userPrompt: string,
  config: EnhancedContractConfig,
  maxIterations: number = 3,
  examples?: string[]
): Promise<ContractGenerationResult> {
  console.log('🚀 Starting iterative contract generation...');
  console.log('📋 Max iterations:', maxIterations);
  
  let contractCode = '';
  let validationResult: ValidationResult | null = null;
  let iteration = 0;
  
  do {
    iteration++;
    console.log(`\n🔄 Iteration ${iteration}/${maxIterations}`);
    
    if (iteration === 1) {
      // First generation
      console.log('🎯 Generating initial contract...');
      contractCode = await generateCompleteContract(userPrompt, config, examples);
    } else {
      // Refinement based on previous errors
      console.log('🔧 Refining contract based on validation feedback...');
      if (!validationResult) {
        throw new Error('Validation result is null during refinement');
      }
      contractCode = await refineContract(contractCode, validationResult, userPrompt, config);
    }
    
    // Validate the generated code
    console.log('🔍 Validating generated contract...');
    validationResult = await validateContractWithAI(contractCode, userPrompt, config);
    
    console.log(`📊 Iteration ${iteration} Results:`);
    console.log(`   ✅ Valid: ${validationResult.valid}`);
    console.log(`   📈 Score: ${validationResult.score}/100`);
    
    if (!validationResult.valid) {
      console.log(`   ❌ Errors: ${validationResult.errors.length}`);
      console.log(`   ❌ Missing features: ${validationResult.missingFeatures.length}`);
      console.log(`   ⚠️ Security issues: ${validationResult.securityIssues.length}`);
    }
    
  } while (!validationResult?.valid && iteration < maxIterations);
  
  if (!validationResult?.valid) {
    console.error(`❌ Failed to generate valid contract after ${maxIterations} iterations`);
    console.error('Final errors:', validationResult?.errors || []);
    throw new Error(`Contract generation failed after ${maxIterations} iterations. Final score: ${validationResult?.score || 0}/100`);
  }
  
  console.log('🎉 Contract generation successful!');
  console.log(`✅ Final score: ${validationResult.score}/100`);
  console.log(`🔄 Iterations used: ${iteration}`);
  
  return {
    contractCode,
    generationMethod: iteration === 1 ? 'ai-initial' : 'ai-refined',
    iteration,
    validationScore: validationResult.score
  };
}

