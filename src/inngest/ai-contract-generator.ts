import { createAgent } from "@inngest/agent-kit";
import { agentModel } from "@/lib/ai/agent-model";
import { EnhancedContractConfig } from '@/types/contract-config';
import { 
  buildContractGenerationPrompt, 
  buildValidationPrompt, 
  buildRefinementPrompt 
} from '@/lib/contract-prompts';

export interface ContractGenerationResult {
  contractCode: string;
  generationMethod: 'ai-initial' | 'ai-refined';
  iteration: number;
  validationScore?: number;
}

export interface ValidationResult {
  valid: boolean;
  errors: string[];
  missingFeatures: string[];
  suggestions: string[];
  securityIssues: string[];
  gasOptimizations: string[];
  score: number;
}

export interface ForgeErrorInfo {
  errors: string[];
  warnings: string[];
  compilationStatus: 'success' | 'failure';
  exitCode: number;
}

/**
 * Generates a complete smart contract using GPT-4.1
 */
export async function generateCompleteContract(
  userPrompt: string,
  config: EnhancedContractConfig,
  examples?: string[]
): Promise<string> {
  console.log('🤖 Generating complete contract with GPT-4.1...');
  
  const prompt = buildContractGenerationPrompt(userPrompt, config, examples);
  
  try {
    const contractGenerator = createAgent({
      name: "Contract-Generator",
      description: "An expert Solidity developer that generates complete smart contracts",
      system: "You are an expert Solidity developer. Generate complete, production-ready smart contracts.",
      model: agentModel("gpt-4.1"),
    });

    // Create timeout promise (5 minutes per AI call)
    const timeoutPromise = new Promise<never>((_, reject) => 
      setTimeout(() => reject(new Error('AI contract generation timeout after 5 minutes')), 300000)
    );

    // Race between AI call and timeout
    const { output } = await Promise.race([
      contractGenerator.run(prompt),
      timeoutPromise
    ]);
    const contractCode = output[0]?.type === "text" ? 
      (Array.isArray(output[0].content) ? output[0].content.join("") : output[0].content) : '';
    
    if (!contractCode) {
      throw new Error('No contract code generated by AI');
    }

    // Clean up the response (remove markdown if present)
    const cleanedCode = contractCode
      .replace(/```solidity\n?/g, '')
      .replace(/```\n?/g, '')
      .trim();

    console.log('✅ Contract generated successfully');
    console.log('📏 Generated code length:', cleanedCode.length);
    
    return cleanedCode;
    
  } catch (error) {
    console.error('❌ Contract generation failed:', error);
    throw new Error(`Contract generation failed: ${error instanceof Error ? error.message : 'Unknown error'}`);
  }
}

/**
 * Validates a contract using AI analysis
 */
export async function validateContractWithAI(
  contractCode: string,
  userPrompt: string,
  config: EnhancedContractConfig
): Promise<ValidationResult> {
  console.log('🔍 Validating contract with AI...');
  
  const prompt = buildValidationPrompt(contractCode, userPrompt, config);
  
  try {
    const contractValidator = createAgent({
      name: "Contract-Validator",
      description: "An expert Solidity auditor that validates smart contracts",
      system: "You are an expert Solidity auditor. Analyze contracts and provide detailed validation feedback.",
      model: agentModel("gpt-4.1"),
    });

    const { output } = await contractValidator.run(prompt);
    const responseText = output[0]?.type === "text" ? 
      (Array.isArray(output[0].content) ? output[0].content.join("") : output[0].content) : '';
    
    if (!responseText) {
      throw new Error('No validation response from AI');
    }

    // Try to parse JSON response
    let validationResult: ValidationResult;
    try {
      // Extract JSON from response (in case it's wrapped in markdown)
      const jsonMatch = responseText.match(/\{[\s\S]*\}/);
      const jsonString = jsonMatch ? jsonMatch[0] : responseText;
      validationResult = JSON.parse(jsonString);
    } catch (parseError) {
      console.error('Failed to parse validation response:', parseError);
      // Fallback to basic validation
      validationResult = {
        valid: false,
        errors: ['Failed to parse AI validation response'],
        missingFeatures: [],
        suggestions: ['Please check the contract manually'],
        securityIssues: [],
        gasOptimizations: [],
        score: 0
      };
    }

    console.log('✅ Contract validation completed');
    console.log('📊 Validation score:', validationResult.score);
    console.log('✅ Valid:', validationResult.valid);
    
    if (!validationResult.valid) {
      console.log('❌ Errors:', validationResult.errors);
      console.log('❌ Missing features:', validationResult.missingFeatures);
    }
    
    return validationResult;
    
  } catch (error) {
    console.error('❌ Contract validation failed:', error);
    throw new Error(`Contract validation failed: ${error instanceof Error ? error.message : 'Unknown error'}`);
  }
}

